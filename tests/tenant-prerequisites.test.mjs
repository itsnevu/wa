test('explicit version gate, fixed fingerprint, deterministic owner, retention and size',async()=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'t01-review-'));
  const statements=[];
  const db=new Database(path.join(dir,'app.db'),{verbose:sql=>statements.push(sql)}); db.pragma('foreign_keys = ON');
  const config={dataDir:dir,adminUser:'fixture',adminPass:'fixture-password-123',migrationBackupKeep:2};
  try {
    await assert.rejects(ensureSchema(db,config),/ALLOW_AUTO_MIGRATE/);
    assert.deepEqual(db.prepare("SELECT name FROM sqlite_master WHERE type='table'").all(),[]);
    await ensureSchema(db,{...config,allowAutoMigrate:true});
    assert.ok(statements.includes('BEGIN IMMEDIATE'));
    const version=db.prepare('SELECT * FROM schema_migrations ORDER BY version DESC LIMIT 1').get();
    assert.equal(version.version,10); assert.equal(version.fingerprint,schemaFingerprint(db));
    assert.equal(db.prepare("SELECT user_id FROM tenant_members WHERE role='owner' AND tenant_id='default'").get().user_id,1);
    await ensureSchema(db,config);
    for(let i=0;i<3;i++) await backupBeforeTenantMigration(db,path.join(dir,'migration-backups'),2);
    const stats=migrationBackupStats(path.join(dir,'migration-backups'));
    assert.equal(stats.backupCount,2);assert.ok(stats.backupBytes>0); console.log('BACKUP_RETENTION',JSON.stringify(stats));
    db.exec('ALTER TABLE numbers ADD COLUMN unexpected TEXT');
    await assert.rejects(ensureSchema(db,{...config,allowAutoMigrate:true}),/fingerprint mismatch/);
    db.exec('UPDATE schema_migrations SET version=999 WHERE version=8');
    await assert.rejects(ensureSchema(db,{...config,allowAutoMigrate:true}),/version mismatch/);
    const unknown=new Database(':memory:'); unknown.exec('CREATE TABLE surprise(id INTEGER)');
    await assert.rejects(ensureSchema(unknown,{...config,allowAutoMigrate:true}),/fingerprint mismatch before/);unknown.close();
  }finally{db.close();fs.rmSync(dir,{recursive:true,force:true});}
});

test('every parent-child INSERT/UPDATE trigger and every immutable tenant UPDATE',()=>{
  const h=twoTenants();const rows=[];
  try {
    for(const table of TENANT_TABLES) {
      const refs=h.db.prepare(`PRAGMA foreign_key_list("${table}")`).all().filter(r=>TENANT_TABLES.includes(r.table));
      if(table==='contacts_v2')refs.push({from:'number_id',table:'numbers',to:'id'});
      for(const ref of refs) {
        const original=h.db.prepare(`SELECT * FROM "${table}" WHERE tenant_id='A' LIMIT 1`).get();
        const other=h.db.prepare(`SELECT "${ref.to}" v FROM "${ref.table}" WHERE tenant_id='B' LIMIT 1`).get().v;
        const copy={...original,[ref.from]:other};
        assert.throws(()=>h.db.prepare(`INSERT INTO "${table}"(${Object.keys(copy).map(n=>`"${n}"`).join(',')}) VALUES(${Object.keys(copy).map(()=>'?').join(',')})`).run(...Object.values(copy)),/tenant relationship mismatch/,`${table}.${ref.from} INSERT`);
        assert.throws(()=>h.db.prepare(`UPDATE "${table}" SET "${ref.from}"=? WHERE tenant_id='A'`).run(other),/tenant relationship mismatch/,`${table}.${ref.from} UPDATE`);
        for(const event of ['INSERT','UPDATE'])assert.ok(h.db.prepare('SELECT 1 FROM sqlite_master WHERE type=\'trigger\' AND name=?').get(`tenant_${table}_${ref.from}_${event}`));
        rows.push(`| ${ref.table}.${ref.to} | ${table}.${ref.from} | INSERT + UPDATE | PASS / PASS |`);
      }
      assert.throws(()=>h.db.prepare(`UPDATE "${table}" SET tenant_id='B' WHERE tenant_id='A'`).run(),/tenant/,`${table}.tenant_id UPDATE`);
      rows.push(`| tenants.id (immutable) | ${table}.tenant_id | UPDATE | PASS |`);
    }
    fs.writeFileSync('docs/t01/trigger-matrix.md','# T01 trigger matrix\n\nGenerated by `node --test tests/tenant-prerequisites.test.mjs`. Every listed pair is executed independently. User membership/assignee validation remains T06. activity has no resource FK in the legacy schema; its tenant immutability is tested.\n\n| Parent | Child | Event | Result |\n|---|---|---|---|\n'+rows.join('\n')+'\n');
    console.log('TRIGGER_MATRIX',rows.length,'pairs/immutability checks; numbers.tenant_id and media_records included');
  }finally{h.close();}
});
