import assert from 'node:assert/strict';
import {setup, incomingHarness, check} from './phase-harness.mjs';
check(['src/db.js','src/routes.js','src/wa.js','public/sw.js']);
const h = await setup('inbox');
try {
  const agent = await h.agent('inbox-agent');
  const outsider = await h.agent('outside-agent');
  const number = h.number(agent.id);
  const chat = Number(h.q.insertChat.run(number,'123456789@lid','Pelanggan',Date.now()).lastInsertRowid);
  const patch = (status,cookie=agent.cookie) => h.request(`/chats/${chat}/status`,'PATCH',{status},cookie);
  assert.equal(h.q.chatById.get(chat).status,'new');
  assert.equal((await patch('invalid')).status,400);
  assert.equal((await patch('resolved',outsider.cookie)).status,403);
  assert.equal((await patch('in_progress')).status,200);
  assert.equal(h.q.chatById.get(chat).status,'in_progress');
  h.q.setAssignee.run(agent.id,chat);
  h.q.setChatUnread.run(2,chat);
  h.q.insertMessage.run(number,chat,0,'Preview pelanggan',Date.now(),null,'text',null,null,'preview-1');
  let rows = await h.json(`/numbers/${number}/chats?queue=mine&status=in_progress`,agent.cookie);
  assert.equal(rows.length,1);
  assert.equal(rows[0].last_body,'Preview pelanggan');
  assert.equal(rows[0].assignee_name,'inbox-agent');
  assert.equal((await h.json(`/numbers/${number}/chats?queue=unassigned`,agent.cookie)).length,0);
  assert.equal((await h.json(`/numbers/${number}/chats?queue=unread`,agent.cookie)).length,1);
  await h.request(`/chats/${chat}/read`,'POST',{},agent.cookie);
  assert.equal((await h.json(`/numbers/${number}/chats?queue=unread`,agent.cookie)).length,0);
  assert.equal((await h.request(`/numbers/${number}/chats?queue=invalid`,'GET',undefined,agent.cookie)).status,400);
  await patch('resolved');
  const socket = await incomingHarness(h,number);
  await socket.send({id:'inbox-reopen',body:'Pelanggan menghubungi lagi'});
  assert.equal(h.q.chatById.get(chat).status,'new');
  assert.equal(h.q.chatById.get(chat).unread,1);
  await patch('resolved');
  await socket.send({id:'inbox-reopen',body:'Duplikat'});
  assert.equal(h.q.chatById.get(chat).status,'resolved');
  await socket.send({id:'inbox-own',body:'Pesan sendiri',fromMe:true});
  assert.equal(h.q.chatById.get(chat).status,'resolved');
  assert.equal((await h.request(`/numbers/${number}/chats`,'GET',undefined,outsider.cookie)).status,403);
  console.log('PASS: status persistence, validation, access, queue filters, previews, read removal, incoming reopen, duplicate and own-message behavior');
} finally { await h.close(); }
